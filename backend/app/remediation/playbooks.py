def render(fix: Fix, server: dict | None) -> dict:
    """Fill a fix's templates for one server (software, host, port, domain)."""
    server = server or {}
    host = server.get("hostname") or "mail.example.org"
    domain = host.split(".", 1)[1] if host.count(".") >= 2 and not host[0].isdigit() else host
    port = server.get("port") or 25
    protocol = server.get("protocol") or "SMTP"
    values = {
        "host": host, "domain": domain, "port": port,
        "starttls": _STARTTLS_FLAG.get(protocol, "smtp"),
    }

    software = server.get("key") or ("generic_smtp" if protocol == "SMTP" else "generic_mailbox")
    chosen = fix.snippets.get(software)
    matched = chosen is not None
    if chosen is None:
        family = "generic_smtp" if protocol == "SMTP" else "generic_mailbox"
        chosen = fix.snippets.get(family, [])
    common = fix.snippets.get("_all", [])

    def fill(text: str) -> str:
        try:
            return text.format(**values)
        except (KeyError, IndexError, ValueError):
            return text

    def snippet(sn: Snippet) -> dict:
        return {
            "file": fill(sn.file),
            "lang": sn.lang,
            "lines": [{"op": op, "text": fill(t) if "{" in t and "${" not in t else t} for op, t in sn.lines],
            "apply": [fill(a) for a in sn.apply],
            "note": fill(sn.note) if sn.note else None,
        }

    # Implicit-TLS ports have no STARTTLS step in verification commands.
    verify = [fill(v) for v in fix.verify]
    if port in (465, 993, 995):
        verify = [v.replace(f"-starttls {values['starttls']} ", "") for v in verify]

    return {
        "id": fix.id,
        "title": fix.title,
        "summary": fix.summary,
        "owner": fix.owner,
        "effort": fix.effort,
        "effort_label": EFFORT_LABEL[fix.effort],
        "group": fix.group,
        "standards": fix.standards,
        "rationale": fix.rationale,
        "resolves": sorted(fix.resolves),
        "software": {
            "key": software, "name": server.get("name"), "version": server.get("version"),
            "evidence": server.get("evidence"), "specific": matched,
        },
        "target": {"server": server.get("server"), "host": host, "port": port, "domain": domain},
        "snippets": [snippet(s) for s in chosen + common],
        "verify": verify + [
            "Re-capture the same traffic and upload it: the Drift view compares the new posture to this one.",
        ],
        "expected_outcome": fix.expected_outcome,
        "caution": fix.caution,
    }
