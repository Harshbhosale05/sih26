"""Remediation playbooks: what to change, in which file, for which software.

Each fix is data, not prose generated on the fly:

  * which finding categories it resolves (so the simulator knows what to apply),
  * who owns it and how much effort it is (so the planner can order the work),
  * the exact configuration change per server product, as a diff,
  * the command that proves the change took effect, and
  * the standard that makes it the right change.

Templates are filled with the observed hostname, port and domain, so an
administrator can paste them. Nothing here is generated by a language model;
every line was written against the product's documented configuration syntax.
"""

from __future__ import annotations

from dataclasses import dataclass, field

EFFORT_LABEL = {1: "Low — configuration change", 2: "Medium — change + coordination", 3: "High — upgrade or migration"}


@dataclass
class Snippet:
    file: str
    lines: list[tuple[str, str]]          # ("+", "line") | ("-", "line") | (" ", "context")
    apply: list[str] = field(default_factory=list)
    note: str | None = None
    lang: str = "ini"


@dataclass
class Fix:
    id: str
    title: str
    summary: str
    resolves: set[str]
    owner: str
    effort: int
    group: str
    standards: list[str]
    rationale: str
    snippets: dict[str, list[Snippet]]
    verify: list[str]
    expected_outcome: str
    caution: str | None = None
    simulated: bool = True


def _s(file: str, *lines: str, apply: list[str] | None = None, note: str | None = None,
       lang: str = "ini") -> Snippet:
    parsed = []
    for line in lines:
        op, text = (line[0], line[2:]) if line[:2] in ("+ ", "- ", "  ") else (" ", line)
        parsed.append((op, text))
    return Snippet(file=file, lines=parsed, apply=apply or [], note=note, lang=lang)


FIXES: dict[str, Fix] = {}


def _fix(fix: Fix) -> None:
    FIXES[fix.id] = fix


